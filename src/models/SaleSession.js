import mongoose from 'mongoose';
import { defineModel } from '../db/defineModel.js';
import generateSessionNumber from '../utils/sessionNumber.js';

// ─── Totals sub-schema ────────────────────────────────────────────────────────

const totalsSchema = new mongoose.Schema(
  {
    cashSales:           { type: Number, default: 0 },
    cardSales:           { type: Number, default: 0 },
    onlineTransferSales: { type: Number, default: 0 },
    storeCreditSales:    { type: Number, default: 0 },
    foodPandaSales:      { type: Number, default: 0 },
    allowanceSales:      { type: Number, default: 0 },
    allowanceOrders:     { type: Number, default: 0 },
    chargeToSalarySales: { type: Number, default: 0 },
    chargeToSalaryOrders:{ type: Number, default: 0 },
    splitBillOrders:     { type: Number, default: 0 },
    totalSales:          { type: Number, default: 0 },
    totalTransactions:   { type: Number, default: 0 },
    totalRefunds:        { type: Number, default: 0 },
    // netCash = cashSales − cash portion of refunds
    netCash:             { type: Number, default: 0 },
    // Membership / Rewards activity for this shift. All zero when the
    // membershipRewards feature was off all session.
    pointsRedeemed:      { type: Number, default: 0 },
    pointsRedeemedValue: { type: Number, default: 0 },
    pointsEarned:        { type: Number, default: 0 },
    rewardsTransactions: { type: Number, default: 0 },
    // Gross sales = totalSales + pointsRedeemedValue (what bills added up to
    // before redemption). Stored explicitly so the Sessions page can show it
    // without having to recompute on every render.
    grossSales:          { type: Number, default: 0 },
    // Operational drawer-count movements. Persisted on close so management can
    // reconcile the physical till; these values do not post to accounting.
    paidOut:             { type: Number, default: 0 },
    paidIn:              { type: Number, default: 0 },
  },
  { _id: false }
);

// ─── Cash drawer movement sub-schema ───────────────────────────────────────────
// An operational cash-count event during the shift. `journalEntry` is retained
// only for legacy rows created before drawer movements stopped posting accounts.

const drawerMovementSchema = new mongoose.Schema(
  {
    type:   { type: String, enum: ['payout', 'cash_in'], required: true },
    amount: { type: Number, required: true, min: 0.01 },
    reason: { type: String, trim: true, maxlength: 300 },
    journalEntry: { type: mongoose.Schema.Types.ObjectId, ref: 'JournalEntry' },
    // Set when the cash movement was created by the POS employee-advance flow.
    // Linked movements are immutable: editing/deleting the drawer row alone
    // would make the physical till disagree with payroll and accounting.
    salaryAdvance: { type: mongoose.Schema.Types.ObjectId, ref: 'SalaryAdvance' },
    by:     { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    at:     { type: Date, default: Date.now },
  },
  { _id: true }
);

// ─── SaleSession schema ────────────────────────────────────────────────────────

const saleSessionSchema = new mongoose.Schema(
  {
    sessionNumber: {
      type: String,
      unique: true,
      trim: true,
      // auto-generated by pre-save hook
    },
    outlet: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Outlet',
      required: [true, 'Outlet is required.'],
    },
    cashier: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: [true, 'Cashier is required.'],
    },
    // Retain the shift owner's name when their login account is later deleted.
    cashierName: { type: String, trim: true },
    openedAt: {
      type: Date,
      default: Date.now,
    },
    closedAt: {
      type: Date,
    },
    openingFloat: {
      type: Number,
      default: 0,
      min: 0,
    },
    closingFloat: {
      type: Number,
      min: 0,
    },
    status: {
      type: String,
      enum: ['open', 'closed'],
      default: 'open',
    },
    totals: {
      type: totalsSchema,
      default: () => ({}),
    },
    // Petty-cash drawer movements recorded during the shift.
    drawerMovements: {
      type: [drawerMovementSchema],
      default: [],
    },
    notes: {
      type: String,
      trim: true,
    },
  },
  { timestamps: true }
);

// ─── Indexes ──────────────────────────────────────────────────────────────────

saleSessionSchema.index({ outlet: 1, status: 1 });
saleSessionSchema.index({ cashier: 1, status: 1 });
saleSessionSchema.index({ openedAt: -1 });

// ─── Pre-save: auto-generate session number ────────────────────────────────────

saleSessionSchema.pre('save', async function () {
  if (!this.isNew || this.sessionNumber) return;
  this.sessionNumber = await generateSessionNumber();
});

const SaleSession = defineModel('SaleSession', saleSessionSchema);

export default SaleSession;
